def evidence(text: str | None, lang: str) -> str | None:
    if not text or lang != "pt":
        return text
    for prefix, template in EVIDENCE_PT:
        if text.startswith(prefix):
            return template.format(rest=text[len(prefix):])
    return text


def translator(lang: str):
    table = STRINGS.get(lang, STRINGS[DEFAULT])

    def t(key: str, **kw) -> str:
        text = table.get(key) or STRINGS["en"].get(key) or key
        return text.format(**kw) if kw else text

    return t


def note(text: str | None, lang: str) -> str | None:
    if not text or lang != "pt":
        return text
    for prefix, translated in NOTES_PT.items():
        if text.startswith(prefix):
            return translated
    return text


def pick_lang(query: str | None, cookie: str | None, accept: str | None) -> str:
    for candidate in (query, cookie):
        if candidate in LANGS:
            return candidate
    if accept and accept.lower().startswith("en"):
        return "en"
    return DEFAULT
