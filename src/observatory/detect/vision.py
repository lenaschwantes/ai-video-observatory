"""Visual signal: a multimodal model inspects the keyframes and must point
at concrete, frame-level evidence for its estimate.

Providers: Groq, Anthropic, OpenAI and Google Gemini. The live analyzer uses
whichever key is set (VISION_PROVIDER forces one); the benchmark calls each
provider explicitly through `assess_with`."""

from __future__ import annotations

import base64
import math
import os
import statistics
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Literal

from pydantic import BaseModel, ValidationError

from observatory.detect.models import Direction, Evidence, Frame, Signal

PROMPT = """You are a forensic analyst estimating whether a short video was generated by an AI video model.
You see {n} keyframes, in order, each labelled with its index and timestamp.

Look for generator artifacts: impossible anatomy (hands, teeth, ears), objects that merge or morph,
physics that breaks (liquids, cloth, hair), garbled text or logos, inconsistent lighting or shadows,
waxy skin, background details that do not persist between frames, and the polished "render" look
typical of current generators. Also look for counter-evidence of a real recording: natural sensor
noise, motion blur consistent with the camera, legible text, persistent fine details.

Calibrate carefully:
- Cartoons, CGI, games, heavy filters and compression are NOT evidence of AI generation by themselves.
- Low resolution limits what you can see; say so and stay near 0.5 instead of guessing.
- Every finding must name the frame index and describe what is visible there.

Return ai_likelihood between 0 and 1."""

JSON_INSTRUCTIONS = """
Answer with a single JSON object and nothing else, in this shape:
{"ai_likelihood": <number 0-1>, "findings": [{"frame_index": <int>, "observation": "<what is visible>", "direction": "ai" | "human" | "neutral"}], "summary": "<one or two sentences>"}"""


class Finding(BaseModel):
    frame_index: int
    observation: str
    direction: Literal["ai", "human", "neutral"]


class VisualAssessment(BaseModel):
    ai_likelihood: float
    findings: list[Finding]
    summary: str


@dataclass
class Usage:
    input_tokens: int = 0
    output_tokens: int = 0
    calls: int = 0
    seconds: float = 0.0

    def add(self, other: "Usage") -> None:
        self.input_tokens += other.input_tokens
        self.output_tokens += other.output_tokens
        self.calls += other.calls
        self.seconds += other.seconds


@dataclass(frozen=True)
class ProviderSpec:
    key_env: tuple[str, ...]
    model_env: str
    default_model: str | None
    max_images: int | None  # per request; frames are batched above this


PROVIDERS: dict[str, ProviderSpec] = {
    "groq": ProviderSpec(("GROQ_API_KEY",), "GROQ_VISION_MODEL", "qwen/qwen3.8-27b", 3),
    "anthropic": ProviderSpec(("ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN"), "OBSERVATORY_MODEL", "claude-opus-5-5", None),
    # No defaults: model names change often, set the one you want to test.
    "openai": ProviderSpec(("OPENAI_API_KEY",), "OPENAI_VISION_MODEL", None, None),
    "gemini": ProviderSpec(("GEMINI_API_KEY", "GOOGLE_API_KEY"), "GEMINI_VISION_MODEL", None, None),
}


def has_key(name: str) -> bool:
    return any(os.environ.get(k) for k in PROVIDERS[name].key_env)


def model_for(name: str) -> str | None:
    spec = PROVIDERS[name]
    return os.environ.get(spec.model_env) or spec.default_model


def provider() -> str | None:
    """Provider used by the live analyzer."""
    forced = os.environ.get("VISION_PROVIDER")
    if forced:
        return forced
    for name in ("groq", "anthropic"):
        if has_key(name):
            return name
    return None


def model_name() -> str:
    name = provider()
    return (model_for(name) if name else None) or "none"


# --- request builders ------------------------------------------------------


def _b64(path: Path) -> str:
    return base64.standard_b64encode(path.read_bytes()).decode("utf-8")


def _parse(raw: str) -> VisualAssessment:
    try:
        return VisualAssessment.model_validate_json(raw)
    except ValidationError as exc:
        raise RuntimeError(f"model returned JSON outside the contract: {exc.errors()[:2]}") from exc


def _call_anthropic(model: str, frames: list[Frame], frame_dir: Path, api_key: str | None = None) -> tuple[VisualAssessment, Usage]:
    import anthropic

    content: list[dict] = []
    for f in frames:
        content.append({"type": "text", "text": f"Frame {f.index} at {f.timestamp:.1f}s"})
        content.append({"type": "image", "source": {"type": "base64", "media_type": "image/jpeg", "data": _b64(frame_dir / f.file)}})
    content.append({"type": "text", "text": PROMPT.format(n=len(frames))})
    response = anthropic.Anthropic(api_key=api_key).beta.messages.parse(
        model=model,
        max_tokens=16000,
        output_config={"effort": "high"},
        betas=["server-side-fallback-2026-07-01"],
        fallbacks="default",
        messages=[{"role": "user", "content": content}],
        output_format=VisualAssessment,
    )
    if response.stop_reason == "refusal" or response.parsed_output is None:
        raise RuntimeError(f"model declined or returned no assessment (stop_reason={response.stop_reason})")
    return response.parsed_output, Usage(response.usage.input_tokens, response.usage.output_tokens, 1)


def _openai_style_content(frames: list[Frame], frame_dir: Path) -> list[dict]:
    content: list[dict] = []
    for f in frames:
        content.append({"type": "text", "text": f"Frame {f.index} at {f.timestamp:.1f}s"})
        content.append({"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{_b64(frame_dir / f.file)}"}})
    content.append({"type": "text", "text": PROMPT.format(n=len(frames)) + JSON_INSTRUCTIONS})
    return content


def _call_groq(model: str, frames: list[Frame], frame_dir: Path, api_key: str | None = None) -> tuple[VisualAssessment, Usage]:
    from groq import Groq

    completion = Groq(api_key=api_key, max_retries=5).chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": _openai_style_content(frames, frame_dir)}],
        response_format={"type": "json_object"},
    )
    u = completion.usage
    return _parse(completion.choices[0].message.content or ""), Usage(u.prompt_tokens, u.completion_tokens, 1)


def _call_openai(model: str, frames: list[Frame], frame_dir: Path, api_key: str | None = None) -> tuple[VisualAssessment, Usage]:
    from openai import OpenAI

    completion = OpenAI(api_key=api_key, max_retries=5).chat.completions.create(
        model=model,
        messages=[{"role": "user", "content": _openai_style_content(frames, frame_dir)}],
        response_format={"type": "json_object"},
    )
    u = completion.usage
    return _parse(completion.choices[0].message.content or ""), Usage(u.prompt_tokens, u.completion_tokens, 1)


def _call_gemini(model: str, frames: list[Frame], frame_dir: Path, api_key: str | None = None) -> tuple[VisualAssessment, Usage]:
    from google import genai
    from google.genai import types

    parts: list = []
    for f in frames:
        parts.append(f"Frame {f.index} at {f.timestamp:.1f}s")
        parts.append(types.Part.from_bytes(data=(frame_dir / f.file).read_bytes(), mime_type="image/jpeg"))
    parts.append(PROMPT.format(n=len(frames)) + JSON_INSTRUCTIONS)
    response = genai.Client(api_key=api_key).models.generate_content(
        model=model,
        contents=parts,
        config=types.GenerateContentConfig(response_mime_type="application/json"),
    )
    meta = response.usage_metadata
    return _parse(response.text or ""), Usage(meta.prompt_token_count or 0, meta.candidates_token_count or 0, 1)


CALLERS: dict[str, Callable[..., tuple[VisualAssessment, Usage]]] = {
    "groq": _call_groq,
    "anthropic": _call_anthropic,
    "openai": _call_openai,
    "gemini": _call_gemini,
}


def merge(results: list[VisualAssessment]) -> VisualAssessment:
    """Average batch estimates in log-odds space and keep every finding."""
    logits = [math.log(p / (1 - p)) for p in (min(max(r.ai_likelihood, 0.02), 0.98) for r in results)]
    mean = statistics.fmean(logits)
    return VisualAssessment(
        ai_likelihood=1 / (1 + math.exp(-mean)),
        findings=[f for r in results for f in r.findings],
        summary=" ".join(r.summary for r in results if r.summary),
    )


def assess_with(name: str, model: str, frames: list[Frame], frame_dir: Path,
                api_key: str | None = None) -> tuple[VisualAssessment, Usage]:
    """Run one provider on the frames, batching when it caps images per request.
    `api_key` overrides the environment for this call only (a visitor's own key)."""
    call = CALLERS[name]
    limit = PROVIDERS[name].max_images or len(frames)
    batches = [frames[i : i + limit] for i in range(0, len(frames), limit)]
    usage, results = Usage(), []
    for batch in batches:
        start = time.perf_counter()
        result, u = call(model, batch, frame_dir, api_key=api_key)
        u.seconds = time.perf_counter() - start
        usage.add(u)
        results.append(result)
    return (results[0] if len(results) == 1 else merge(results)), usage


def assess(frames: list[Frame], frame_dir: Path) -> VisualAssessment:
    name = provider()
    model = model_for(name) if name else None
    if not name or not model:
        raise RuntimeError("no vision provider configured")
    return assess_with(name, model, frames, frame_dir)[0]


def visual_signal(frames: list[Frame], frame_dir: Path, assessor=assess) -> Signal:
    label = "Visual analysis of keyframes"
    if not frames:
        return Signal(name="visual", label=label, available=False, note="No frames could be extracted.")
    if assessor is assess and provider() is None:
        return Signal(name="visual", label=label, available=False, note="Set GROQ_API_KEY or ANTHROPIC_API_KEY to enable it.")
    try:
        result = assessor(frames, frame_dir)
    except Exception as exc:
        return Signal(name="visual", label=label, available=False, note=f"Visual analysis failed: {exc}")

    p = min(max(result.ai_likelihood, 0.02), 0.98)
    by_index = {f.index: f for f in frames}
    evidence = [
        Evidence(
            text=f.observation,
            direction=Direction(f.direction),
            timestamp=by_index[f.frame_index].timestamp if f.frame_index in by_index else None,
            frame=by_index[f.frame_index].file if f.frame_index in by_index else None,
        )
        for f in result.findings
    ]
    note = f"{result.summary} (model: {model_name()})" if assessor is assess else result.summary
    # Shrink the model's log-odds: an uncalibrated judge should not dominate.
    return Signal(name="visual", label=label, available=True, llr=0.8 * math.log(p / (1 - p)), evidence=evidence, note=note)
