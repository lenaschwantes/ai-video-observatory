OUT = Path(__file__).with_name("dataset.csv")
FIELDS = ["id", "url", "label", "region", "label_source", "upload_date", "height", "duration", "channel", "title"]


def main() -> None:
    import yt_dlp

    rows = []
    with yt_dlp.YoutubeDL({"quiet": True, "no_warnings": True, "skip_download": True}) as ydl:
        groups = (("ai", "global", AI), ("real", "global", REAL), ("ai", "br", BR_AI), ("real", "br", BR_REAL))
        for label, region, ids in groups:
            for vid in ids:
                time.sleep(3)  # stay under YouTube's burst limit
                url = f"https://www.youtube.com/watch?v={vid}"
                try:
                    info = ydl.extract_info(url, download=False)
                except yt_dlp.utils.DownloadError as exc:
                    print(f"skip {vid}: {exc}")
                    continue
                rows.append(
                    {
                        "id": vid,
                        "url": url,
                        "label": label,
                        "region": region,
                        "label_source": "uploader names the generator" if label == "ai" else "uploaded before 2022",
                        "upload_date": info.get("upload_date"),
                        "height": info.get("height"),
                        "duration": info.get("duration"),
                        "channel": info.get("channel"),
                        "title": info.get("title"),
                    }
                )
                print(f"{label:4} {vid} {info.get('title')}")
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
